/**
 * Area landing pages.
 *
 * IMPORTANT — the slugs here are the exact URLs the previous WordPress site had
 * indexed (`/location/<slug>/`). They are served, not redirected, so the pages
 * keep their existing Google authority instead of losing some of it through a
 * 301. Do not rename an existing slug; add new ones only.
 *
 * `peiraias` is new — it had no equivalent on the old site, but it is where the
 * network actually has garages today.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * HONESTY RULE — read before editing.
 *
 * These pages must never imply garage coverage that doesn't exist. `coverage`
 * drives a visible notice at the top of every area page:
 *
 *   'active'    → we have at least one registered garage serving this area
 *   'expanding' → we have none yet; the page says so, in the first screen
 *
 * As of 2026-08-11 the network is three garages: two in Κερατσίνι and one in
 * Άγιο Δημήτριο. UPDATE `coverage` WHEN THAT CHANGES — it is the one field here
 * that can silently turn into a false claim. Everything else on these pages is
 * either general information about servicing a car in the area or a statement
 * about how the platform works, neither of which depends on garage count.
 * ─────────────────────────────────────────────────────────────────────────────
 */

export interface AreaFaq {
  question: string
  answer: string
}

export interface Area {
  /** URL segment under /location/ — legacy slugs must not change */
  slug: string
  /** Short name used in headings and breadcrumbs */
  name: string
  /** Prepositional form, for "συνεργείο <X>" style copy */
  nameGenitive: string
  /** Region this belongs to, for schema areaServed */
  region: string
  /** Whether any registered garage currently serves this area. See HONESTY RULE. */
  coverage: 'active' | 'expanding'
  /** Where the active garages are, shown on 'active' pages. Empty when expanding. */
  activeIn: string[]
  title: string
  description: string
  /** Opening paragraph — general, factual information about the area */
  intro: string
  /** Second paragraph covering how the marketplace works */
  detail: string
  /** Municipalities and neighbourhoods the area covers */
  neighbourhoods: string[]
  /** Services commonly needed here */
  commonServices: string[]
  faqs: AreaFaq[]
}

