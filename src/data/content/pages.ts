/**
 * The copy every marketing page ships with.
 *
 * This is the floor the CMS overrides, not a set of placeholders: it is the
 * exact text these pages rendered when it was hardcoded in the components. An
 * empty SiteContent table, a DynamoDB outage or a bad deploy therefore leaves
 * the public site reading exactly as it does today. See src/lib/site-content.ts.
 *
 * Block ids are stable and hand-written. The editor reorders and edits blocks
 * by id, so changing one here orphans that block's edits.
 */

const b = {
  heading: (id: string, text: string): ContentBlock => ({ id, type: 'heading', text }),
  paragraph: (id: string, text: string): ContentBlock => ({ id, type: 'paragraph', text }),
  list: (id: string, items: string[]): ContentBlock => ({ id, type: 'list', items }),
  cta: (id: string, label: string, href: string, variant: 'primary' | 'secondary' = 'primary'): ContentBlock =>
    ({ id, type: 'cta', label, href, variant }),
  callout: (id: string, tone: 'info' | 'warning', text: string): ContentBlock =>
    ({ id, type: 'callout', tone, text }),
}

