/**
 * FAQ content, shared by the homepage FAQ section and the dedicated /faq/ page.
 *
 * `faqs` is the featured subset rendered on the landing page. `faqCategories`
 * is the full set — /faq/ is a superset, so both pages can legitimately carry
 * FAQPage schema for the questions they actually display.
 *
 * These answers are the single biggest AI-search asset the site has: assistants
 * quote question-shaped passages far more readily than marketing copy. Keep
 * answers self-contained — an answer that only makes sense in the context of
 * the surrounding page is useless once it's extracted.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * HONESTY RULE — the answers in the 'booking' category describe the platform as
 * taking NO payment from the customer: they book for free and pay the garage
 * directly for the work. That is true only while `NEXT_PUBLIC_PAYMENTS_ENABLED`
 * is off. The Stripe deposit flow is built and gated behind that flag
 * (`RequestDetailsContent`, `CancellationModal`, `ProfilePage`, and the
 * `payments/*` API routes all check it).
 *
 * THE DAY THAT FLAG IS TURNED ON, "Πληρώνω για να κλείσω ραντεβού; Όχι."
 * BECOMES FALSE and must be rewritten to describe the deposit. Search engines
 * and AI assistants will have cached and be quoting the old answer, so this is
 * not a cosmetic edit — update it in the same change that enables payments.
 * ─────────────────────────────────────────────────────────────────────────────
 */

